"""Prepare and verify local CSV quality reports and JSON conversions in Scout Inbox."""
import csv
from hashlib import sha256
import io
from itertools import islice
import os
from pathlib import Path
import re
import stat
from .digital_deliverable import (MAX_INPUT_BYTES, MAX_ROWS, MAX_COLUMNS, MAX_OUTPUT_BYTES, PROFILE_COLUMNS,
                                  CSV_SOURCE, JSON_SOURCE, DeliverableError, _cell, _permit, _profile_rows,
                                  _verify_profile, _serialize, _string_records, _table)
from .deliverable_files import read_selected_csv, read_published_csv, publish_new_csv

INBOX = "Scout Inbox"
OUTPUTS = "Scout Outputs"


def folder(directory, name):
    if name not in (INBOX, OUTPUTS):
        raise ValueError("Unknown work folder.")
    path = Path(directory).resolve() / name
    path.mkdir(exist_ok=True)
    info = path.lstat()
    if (not stat.S_ISDIR(info.st_mode) or path.is_symlink()
            or getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT):
        raise ValueError("Expected a local work directory.")
    return path


def check_columns(cols):
    if (not 1 <= len(cols) <= MAX_COLUMNS or len(set(cols)) != len(cols)
            or not all(re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,39}", col) for col in cols)):
        raise DeliverableError("INVALID_COLUMN_SCHEMA")


def profile_csv(raw, stopped):
    if not 0 < len(raw) <= MAX_INPUT_BYTES:
        raise DeliverableError("CSV_BYTE_LIMIT")
    reader = csv.reader(io.StringIO(raw.decode("utf-8-sig"), newline=""), strict=True)
    cols = next(reader, [])
    check_columns(cols)
    records = {}
    for index, row in enumerate(reader):
        _permit(False, stopped)
        if index >= MAX_ROWS or len(row) != len(cols):
            raise DeliverableError("CSV_ROW_LIMIT_OR_WIDTH")
        records[index] = tuple(_cell(cell) for cell in row)
    if not records:
        raise DeliverableError("CSV_NO_ROWS")
    spec = dict(columns=cols)
    output = _profile_rows(spec, records, False, stopped)
    schema = dict(columns=list(PROFILE_COLUMNS), key_column="column", expected_rows=len(cols))
    artifact = _serialize(schema, output, False, stopped)
    checked = _table(artifact, schema, maximum=MAX_OUTPUT_BYTES, ordered=True, halted=False, halt_check=stopped)
    _verify_profile(spec, records, checked, False, stopped)
    return artifact


def convert_json(raw, stopped):
    if not 0 < len(raw) <= MAX_INPUT_BYTES:
        raise DeliverableError("JSON_BYTE_LIMIT")
    items = _string_records(raw.removeprefix(b"\xef\xbb\xbf"), False, stopped)
    if type(items) is not list or not 1 <= len(items) <= MAX_ROWS or type(items[0]) is not dict:
        raise DeliverableError("JSON_ROW_COUNT_OR_SHAPE_MISMATCH")
    cols = list(items[0])
    check_columns(cols)
    rows = {}
    for i, record in enumerate(items):
        _permit(False, stopped)
        if type(record) is not dict or record.keys() != items[0].keys():
            raise DeliverableError("JSON_RECORD_SCHEMA_MISMATCH")
        rows[i] = tuple(_cell(record[col]) for col in cols)
    artifact = _serialize({"columns": cols}, rows, False, stopped)
    # Re-open the generated bytes and compare every field to the source, in input order.
    reader = csv.reader(io.StringIO(artifact.decode("utf-8"), newline=""), strict=True)
    if next(reader, None) != cols:
        raise DeliverableError("CSV_CONTENT_MISMATCH")
    for record in items:
        _permit(False, stopped)
        if next(reader, None) != [record[col] for col in cols]:
            raise DeliverableError("CSV_CONTENT_MISMATCH")
    if next(reader, None) is not None:
        raise DeliverableError("CSV_CONTENT_MISMATCH")
    return artifact


