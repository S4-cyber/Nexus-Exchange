def work_file(path, out, stopped):
    is_json = path.suffix.lower() == ".json"
    label = "".join(ch if ch.isprintable() else "�" for ch in path.name)
    item = dict(name=label, operation="JSON to CSV" if is_json else "Column quality report")
    try:
        raw = read_selected_csv(path, halted=False, halt_check=stopped, source_format=JSON_SOURCE if is_json else CSV_SOURCE)
        artifact = convert_json(raw, stopped) if is_json else profile_csv(raw, stopped)
        prefix = re.sub(r"[^A-Za-z0-9_-]", "_", path.stem)[:32] or "file"
        kind = "records" if is_json else "quality"
        dest = out / (prefix + "-" + kind + "-" + sha256(raw).hexdigest()[:16] + ".csv")
        if os.path.lexists(dest):
            if read_published_csv(dest, halted=False, halt_check=stopped) != artifact:
                raise DeliverableError("OUTPUT_CONTENT_CHANGED")
            status = "existing"
        else:
            publish_new_csv(dest, artifact, halted=False, halt_check=stopped)
            status = "produced"
        return dict(item, status=status, output=dest.name)
    except DeliverableError as exc:
        reason = _REASONS.get(str(exc), "Scout could not verify the input or publish its output.")
    except (UnicodeError, csv.Error):
        reason = "Save the file as UTF-8 with valid CSV quoting."
    except OSError:
        _permit(False, stopped)
        reason = "Check the work folders and local file permissions."
    return dict(item, status="held", reason=reason)


def run_files(directory, stopped, *, report=None):
    _permit(False, stopped)
    counts = dict(produced=0, existing=0, held=0, full=False, items=[])
    try:
        inbox, out = folder(directory, INBOX), folder(directory, OUTPUTS)
        with os.scandir(inbox) as scan:
            entries = list(islice(scan, 129))
    except (OSError, ValueError):
        counts["issue"] = "Scout could not access its work folders. Check the local folders and their permissions."
        return counts
    if len(entries) > 128:
        counts["full"] = True
        return counts
    paths = sorted((Path(entry.path) for entry in entries if Path(entry.name).suffix.lower() in (".csv", ".json")),
                   key=lambda path: (path.name.casefold(), path.name))
    def update(rows):
        if report:
            report([("file-" + sha256(os.fsencode(path.name)).hexdigest(), state,
                     "".join(c if c.isprintable() else "�" for c in path.name), detail)
                    for path, state, detail in rows])
    update([(path, "Pending", "Queued in Scout Inbox.") for path in paths])
    for path in paths:
        _permit(False, stopped)
        update([(path, "Engaged", "Checking input and preparing the local output.")])
        item = work_file(path, out, stopped)
        status = item["status"]
        detail = (item["reason"] if status == "held" else
                  ("Verified existing output · " if status == "existing" else "Created and verified · ") + item["output"])
        update([(path, "Needs attention" if status == "held" else "Completed", item["operation"] + " · " + detail)])
        counts[item["status"]] += 1
        counts["items"].append(item)
    return counts
